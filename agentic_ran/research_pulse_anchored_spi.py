"""PA-SPI: empirical PULSE-anchored improvement in an interventional TOY only.

All action labels are generated by actual paired synthetic rollouts, never
COMMAG counterfactual fabrication. Bootstrap members resample entire episodes.
The calibration buffers are empirical residual quantiles, not formal guarantees.
"""
from __future__ import annotations

from copy import deepcopy
from dataclasses import dataclass
from typing import Any

import numpy as np
from scipy.spatial import cKDTree
from sklearn.linear_model import Ridge
from sklearn.preprocessing import PolynomialFeatures, StandardScaler

from agentic_ran.research_pulse_ran import select_pulse_ran
from agentic_ran.research_twin_environment import ACTIONS, MultiSliceToyTwin, SLA_QUEUE_LIMITS

N = len(ACTIONS)
TRAIN_SCENARIOS = ("normal", "congested", "bursty")
TEST_SCENARIOS = (*TRAIN_SCENARIOS, "weak_channel", "shifted_fading", "shifted_burst")


class ShiftedTwin(MultiSliceToyTwin):
    """Distinct stress-test dynamics; deliberately not a calibrated NR model."""
    def __init__(self, *, seed: int, scenario: str):
        super().__init__(seed=seed, scenario="weak_channel" if scenario == "shifted_fading" else "bursty")
        self.shift = scenario

    def step(self, action: int):
        if not 0 <= int(action) < N:
            raise ValueError("invalid allocation")
        q, demand, channel = np.split(self.state, 3)
        served = 2.85 * ACTIONS[action] * channel / (1 + .09 * q)
        new_q = np.maximum(0., q + demand - served)
        noise_d = self.rng.normal(0, 1, 3)
        noise_c = self.rng.normal(0, 1, 3)
        burst = (.27 if self.t % 11 in (2, 3, 4) else 0.) if self.shift == "shifted_burst" else 0.
        fade = .16 if self.shift == "shifted_fading" and self.t % 13 in (4, 5, 6) else 0.
        d = np.maximum(.08, .69 * demand + .31 * self.demand_reference + .065 * noise_d
                       + burst * np.array([.6, .2, 1.]))
        ch = np.clip(.72 * channel + .28 * self.channel_reference + .055 * noise_c - fade, .28, 1.4)
        nxt = np.concatenate((new_q, d, ch))
        flags = new_q > SLA_QUEUE_LIMITS
        # Independent reward sensitivity: emphasize tails and switching.
        reward = float(1 - .05 * new_q[0]**2 - .06 * new_q[1]**2 - .27 * new_q[2]**2
                       - np.dot(flags, [.18, .18, .7]) - .08 * (action != self.previous_action)
                       - .028 * np.sum(ACTIONS[action]**2))
        self.state, self.previous_action, self.t = nxt, int(action), self.t + 1
        return nxt.copy(), reward, flags


def make_world(seed: int, scenario: str):
    if scenario in ("shifted_fading", "shifted_burst"):
        return ShiftedTwin(seed=seed, scenario=scenario)
    return MultiSliceToyTwin(seed=seed, scenario=scenario)


def features(state, previous, t):
    s = np.asarray(state, dtype=float)
    if s.shape != (9,) or not np.isfinite(s).all() or not 0 <= int(previous) < N:
        raise ValueError("invalid finite state or prior allocation")
    q, d, ch = np.split(s, 3)
    return np.r_[s, q + d, d / np.maximum(ch, .2), np.eye(N)[int(previous)], np.sin(t/4), np.cos(t/4)]


def _branch(world, action: int, horizon: int):
    env = deepcopy(world)
    value, risk = 0., np.zeros(3)
    for k in range(horizon):
        a = action if k == 0 else select_pulse_ran(env.state)
        _, reward, flags = env.step(a)
        value += .93**k * reward
        risk += flags
    return np.r_[value, risk / horizon]


def samples(seed: int, episodes: int, steps: int, horizon: int):
    """All actions branched at identical TRAIN or CALIBRATION states.

    The exploration RNG is separate from exogenous simulator disturbances.
    No branch labels are generated on the held-out test set.
    """
    rng = np.random.default_rng(seed + 91)
    xs, ys, groups = [], [], []
    for ep in range(episodes):
        world = make_world(seed + ep * 1009, TRAIN_SCENARIOS[ep % len(TRAIN_SCENARIOS)])
        for t in range(steps):
            if t % 2 == 0:
                xs.append(features(world.state, world.previous_action, t))
                ref = select_pulse_ran(world.state)
                outcomes = np.stack([_branch(world, a, horizon) for a in range(N)])
                ys.append(outcomes - outcomes[ref])
                groups.append(ep)
            a = select_pulse_ran(world.state) if rng.random() < .6 else int(rng.integers(N))
            world.step(a)
    return np.asarray(xs), np.asarray(ys), np.asarray(groups)


@dataclass
class PulseSPI:
    scaler: Any
    poly: Any
    members: list
    tree: Any
    support_limit: float
    gain_buffer: np.ndarray
    risk_buffer: np.ndarray
    margin: float = .05
    switch_cost: float = .08
    risk_tolerance: float = .01

    def estimate(self, state, previous, t):
        x = self.scaler.transform(features(state, previous, t)[None, :])
        z = self.poly.transform(x)
        preds = np.stack([m.predict(z)[0].reshape(N, 4) for m in self.members])
        ref = select_pulse_ran(state)
        # Re-anchor predictions exactly at the reference action.
        preds = preds - preds[:, ref:ref+1, :]
        mean, std = preds.mean(0), preds.std(0)
        distance = float(self.tree.query(x[0], k=1)[0])
        return ref, mean, std, distance

    def decide(self, state, previous, t, *, mode="pa_spi"):
        prior = 0 if previous is None else int(previous)
        ref, mean, std, distance = self.estimate(state, prior, t)
        supported = distance <= self.support_limit
        lower = mean[:, 0] - std[:, 0] - self.gain_buffer
        upper_risk = mean[:, 1:] + std[:, 1:] + self.risk_buffer
        lower[ref] = 0.
        upper_risk[ref] = 0.
        eligible = (upper_risk <= self.risk_tolerance).all(axis=1)
        if mode == "pa_no_risk":
            eligible[:] = True
        if mode not in {"pa_no_support", "pa_no_gates"} and not supported:
            eligible[:] = False
        if mode == "pa_no_gates":
            eligible[:] = True
        score = lower.copy() if mode not in {"pa_no_lcb", "pa_no_anchor", "pa_no_gates"} else mean[:, 0].copy()
        # Only incremental switching cost: avoid double-counting the
        # simulator's switching charge already present in rollout returns.
        if mode != "pa_no_switch":
            score -= self.switch_cost * ((np.arange(N) != prior).astype(float) - float(ref != prior))
        score[~eligible] = -np.inf
        score[ref] = 0.
        best = int(np.argmax(score))
        threshold = -np.inf if mode == "pa_no_anchor" else self.margin
        if best != ref and score[best] > threshold:
            action, reason = best, "override"
        else:
            action = ref
            reason = "unsupported_reference_fallback" if not supported else "reference_fallback"
        # The reference is always feasible in this toy. It is NOT guaranteed
        # safe or supported; the audit deliberately records unsupported fallback.
        return action, {"anchor": ref, "reason": reason, "state_support": bool(supported),
                        "support_distance": distance, "eligible_fraction": float(eligible.mean()),
                        "gain_lcb": float(lower[action]), "risk_upper_max": float(upper_risk[action].max())}


def fit(seed: int, episodes: int, validation: int, steps: int, *, horizon: int = 6):
    if episodes < 12 or validation < 4 or steps < 5 or horizon < 1:
        raise ValueError("insufficient train/calibration episodes")
    x, y, groups = samples(seed, episodes, steps, horizon)
    cx, cy, cg = samples(seed + 10_000_000, validation, steps, horizon)
    scaler = StandardScaler().fit(x)
    xx, cc = scaler.transform(x), scaler.transform(cx)
    poly = PolynomialFeatures(2, include_bias=False).fit(xx)
    z, cz = poly.transform(xx), poly.transform(cc)
    rng = np.random.default_rng(seed + 117)
    members = []
    for _ in range(5):
        ids = rng.choice(np.unique(groups), episodes, replace=True)
        idx = np.concatenate([np.flatnonzero(groups == g) for g in ids])
        members.append(Ridge(alpha=8.).fit(z[idx], y[idx].reshape(len(idx), -1)))
    predictions = np.stack([m.predict(cz).reshape(len(cx), N, 4) for m in members])
    # Anchor predictions at the true baseline action (from unscaled state).
    refs = np.array([select_pulse_ran(row[:9]) for row in cx])
    predictions -= predictions[:, np.arange(len(cx)), refs, :][:, :, None, :]
    means, stds = predictions.mean(0), predictions.std(0)
    # Episode-level empirical residual quantiles; descriptive, not conformal
    # conditional coverage. Do not tune these buffers on held-out outcomes.
    gain_res = means[:, :, 0] - stds[:, :, 0] - cy[:, :, 0]
    risk_res = cy[:, :, 1:] - means[:, :, 1:] - stds[:, :, 1:]
    def buffer(res):
        blocks = np.stack([np.quantile(res[cg == g], .90, axis=0) for g in np.unique(cg)])
        return np.maximum(0., np.quantile(blocks, .90, axis=0))
    tree = cKDTree(xx)
    limit = max(float(np.quantile(tree.query(cc, k=1)[0], .95)), 1e-6)
    controller = PulseSPI(scaler, poly, members, tree, limit, buffer(gain_res), buffer(risk_res))
    calibration = {"support_distance_limit": limit, "gain_buffer": controller.gain_buffer.tolist(),
                   "risk_buffer": controller.risk_buffer.tolist(), "train_seed": seed,
                   "calibration_seed": seed + 10_000_000, "branch_horizon": horizon,
                   "training_episodes": episodes, "calibration_episodes": validation,
                   "support_definition": "nearest training state; every feasible action branched in toy only",
                   "formal_safety_certificate": False}
    return controller, calibration
